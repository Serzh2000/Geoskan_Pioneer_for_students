-- число участвует в вычислениях, строка подписывает его в журнале
local height = 2                    -- заданная высота, метры
print("высота, м: " .. height)      -- высота, м: 2

-- склейка .. превращает число в текст; длина строки — #
local name = "Pioneer"
print(#name, name .. "!")           -- 7  Pioneer!
