export function blocklyPracticeSteps(lesson: GuideLesson): string[] {
    if (lesson.id.startsWith('lua-')) return STEPS[blocklyTopic(lesson)] || [];
    return STEPS_PY[blocklyTopic(lesson)] || [];
}

function blocklyTopic(lesson: GuideLesson): string {
    const rawTopic = lesson.id.replace(/^(lua|python|py)-/, '');
    return ({ arm: 'preflight', 'point-wait': 'point-confirm', land: 'landing' } as Record<string, string>)[rawTopic] || rawTopic;
}

export function blocklyLessonCopy(lesson: GuideLesson): GuideLesson {
    const topic = blocklyTopic(lesson);
    const [summary, intro] = TOPICS[topic] || ['Соберите программу из блоков и проверьте результат на сцене.', 'Соединяйте блоки в порядке выполнения. Для действий по событию используйте вложенные блоки обработчика.'];
    const ledSingle = topic === 'led-single';
    const lua = lesson.id.startsWith('lua-');
    return {
        ...lesson,
        summary,
        lessonIntro: ledSingle && lua
            ? 'Добавьте блок создания ленты на 29 светодиодов, а под ним — блок задания цвета LED. Первый светодиод имеет номер 0. В полях цвета задайте: красный — 1, зелёный — 0, синий — 0.'
            : intro,
        goal: `Цель: ${lesson.expectedOutcome.charAt(0).toLowerCase()}${lesson.expectedOutcome.slice(1)}`,
        builderHint: (lua ? HINTS[topic] : HINTS_PY[topic]) || `${intro} Сверяйтесь с ожидаемым результатом задания.`
    };
}

