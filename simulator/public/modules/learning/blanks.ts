/**
 * Заготовки миссий содержат пропуски `___`, которые ученик должен заменить значением. Если нажать «Проверить полёт», не заменив
 * их, программа падает с ошибкой, и ребёнок видит «Есть ошибка запуска», не понимая, что делать. Поэтому пропуски
 * замечаем до запуска и объясняем по-человечески.
 */

/** Код без комментариев: пропуск, упомянутый в пояснении к строке, пропуском не считается. */
function withoutComments(code: string): string {
    return code.split(/\r?\n/).map((line) => line.replace(/(^|\s)(--|#).*$/, '$1')).join('\n');
}

/** Сколько пропусков `___` осталось в программе (отдельным словом, не частью имени вроде `___x` или `a___b`). */
export function countUnfilledBlanks(code: string): number {
    return (withoutComments(code).match(/(?<![A-Za-z0-9_])___(?![A-Za-z0-9_])/g) ?? []).length;
}

export function unfilledBlanksMessage(count: number): { title: string; lines: string[] } {
    return {
        title: count === 1 ? 'В коде остался пропуск ___' : `В коде остались пропуски ___ (${count})`,
        lines: [
            'Вместо каждого ___ впишите значение из задания и снова нажмите «Проверить полёт».',
            'Пока в коде есть ___, программа не запустится, поэтому мы её и не запускаем.'
        ]
    };
}
