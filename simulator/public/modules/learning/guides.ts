/**
 * Шаги миссий, которые ведут ученика по интерфейсу за руку: подсвечивают нужную кнопку и сами засчитывают шаг,
 * когда ученик её нажал. Нужны там, где текст урока отсылает к месту, которого нет на экране миссии
 * (в книге это ссылка под рабочим листом, в режиме обучения книги нет).
 */
export type GuidedStep = {
    text: string;
    /** CSS-селектор элемента, который нужно подсветить. */
    target?: string;
    /** Подпись у подсветки. */
    label?: string;
    /** Шаг засчитывается сам, когда условие выполнено; без него ученик нажимает «Сделал, дальше». */
    until?: () => boolean;
    /** Подсвеченная кнопка лежит в редакторе: перед шагом показать редактор. */
    inEditor?: boolean;
};

type Language = 'lua' | 'python';

const visible = (selector: string): boolean => {
    const node = document.querySelector<HTMLElement>(selector);
    return Boolean(node && !node.hidden && node.getClientRects().length);
};

const docsText = (): string => document.querySelector<HTMLElement>('#editor-docs-body')?.innerText ?? '';

/** Результаты поиска показывают нужную команду: ученик нашёл её сам, по смыслу, а не по названию. */
const found = (language: Language): boolean => {
    const input = document.querySelector<HTMLInputElement>('#api-docs-search');
    if (!input || !input.value.trim()) return false;
    return language === 'lua' ? /MCE_PREFLIGHT/.test(docsText()) : /\barm\b/.test(docsText());
};

/**
 * Урок 7 «Что такое API»: команду, которую нужно вписать, ученик не называет, а ищет в справочнике по смыслу
 * («подготовка двигателей»), как искал бы незнакомую команду. Точное имя в тексте шагов не раскрывается:
 * оно в подсказке на случай, если поиск не получается.
 */
function whatIsApi(language: Language): GuidedStep[] {
    // Слово по смыслу: в каталогах двух языков команда описана разными словами.
    const word = language === 'lua' ? 'подготовка' : 'мотор';
    return [
        {
            text: 'Допустим, вы не помните название команды, которая подготавливает двигатели. Её можно найти в справочнике API. Откройте его: кнопка с книгой в верхней панели редактора подсвечена.',
            target: '#editor-docs-toggle-btn', label: 'Справочник API', inEditor: true,
            until: () => visible('#editor-docs')
        },
        {
            text: `Ищите по смыслу, а не по названию: введите в строку поиска слово «${word}». Справочник ищет и по названиям, и по описаниям.`,
            target: '#api-docs-search', label: `Введите: ${word}`,
            until: () => found(language)
        },
        {
            text: language === 'lua'
                ? 'В результатах найдите команду, которая отправляет автопилоту подготовку к полёту, и раскройте её стрелкой справа. Обратите внимание на запись: у такой команды есть метод и аргумент, который выбирает, какое именно действие выполнить.'
                : 'В результатах найдите метод, который подготавливает двигатели, и раскройте его стрелкой справа. Посмотрите, как он записывается: имя метода и скобки, в которые при необходимости передают аргументы.',
            target: '#editor-docs-body', label: 'Результаты поиска'
        },
        {
            text: language === 'lua'
                ? 'Закройте справочник крестиком и впишите найденное в скобки `ap.push()` в редакторе. Аргумент перепишите из справочника точно, с регистром и точкой.'
                : 'Закройте справочник крестиком и впишите вместо `____` имя найденного метода. Имя перепишите из справочника точно.',
            target: '#editor-docs-close-btn', label: 'Закрыть справочник',
            until: () => !visible('#editor-docs')
        }
    ];
}

/** Проведение за руку по номеру миссии; для остальных миссий шаги берутся из урока как есть. */
export const GUIDED_STEPS: Record<string, (language: Language) => GuidedStep[]> = {
    'academy-007': whatIsApi
};
