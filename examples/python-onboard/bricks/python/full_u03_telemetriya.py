
from pioneer_sdk2 import Pioneer
pioneer = Pioneer()
from time import sleep

print("Начало программы")
try:
    for count in range(10):
      print('Высота по дальномеру, м: ' + str(pioneer.get_dist_sensor_data()))
      sleep(1)
except Exception as e:
    print(e)
finally:
    pio = locals().get("pioneer")
    if pio is not None:
        try:
            pio.wait_callback = False
            pio.land()
            pio.close_connection()
        except Exception:
            pass

    for cam_name in ("cam_main", "cam_opt"):
        cam = locals().get(cam_name)
        if cam is not None:
            try:
                cam.stop()
            except Exception:
                pass

    viewer = locals().get("iv")
    if viewer is not None:
        try:
            viewer.close()
        except Exception:
            pass
        del viewer

    if pio is not None:
        del pio
    print("Конец программы")