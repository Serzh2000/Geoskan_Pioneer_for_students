#!/usr/bin/env node
/*
 * Copies the Tabler icons the UI renders from JS into
 * public/modules/ui/icons/tabler.ts - verbatim path data from the
 * @tabler/icons package (devDependency), so no hand-drawn look-alikes creep
 * in. Icons that live in static HTML fragments are pasted from the same
 * package files directly.
 *
 * Add a name to ICONS and run:  node scripts/generate-tabler-icons.cjs
 */
const fs = require('fs');
const path = require('path');

const ICONS = [
    // scene manager tree rows
    'chevron-right', 'focus-2', 'trash',
    // scene object context menu
    'adjustments',
    // scene object types (tree, catalog, hotbar)
    'antenna', 'bolt', 'box', 'bulb', 'building-community', 'building-skyscraper',
    'car', 'charging-pile', 'christmas-tree', 'device-cctv', 'device-desktop', 'drone',
    'fence', 'flag', 'frame', 'grid-4x4', 'grid-pattern', 'helicopter-landing',
    'lamp-2', 'map-pin', 'mountain', 'package', 'qrcode', 'road', 'square-letter-h',
    'stack-2', 'traffic-cone', 'train', 'trees', 'track', 'car-suv',
    // route drawing HUD
    'route-2', 'check', 'arrow-back-up', 'repeat', 'x', 'player-track-next',
    // building settings: window incidents
    'flame', 'cloud', 'spy', 'eraser', 'dice-5'
];

const root = path.resolve(__dirname, '..');
const srcDir = path.join(root, 'node_modules/@tabler/icons/icons/outline');
const pkg = require(path.join(root, 'node_modules/@tabler/icons/package.json'));
const outFile = path.join(root, 'public/modules/ui/icons/tabler.ts');

function toInlineSvg(name) {
    const file = path.join(srcDir, `${name}.svg`);
    if (!fs.existsSync(file)) throw new Error(`No such Tabler icon: ${name}`);
    return fs.readFileSync(file, 'utf8')
        .replace(/<!--[\s\S]*?-->/g, '')
        .replace(/\s*\n\s*/g, ' ')
        .replace(/\s*\/>/g, '/>')
        .replace(/<svg /, '<svg aria-hidden="true" ')
        .replace(/>\s+</g, '><')
        .trim();
}

const entries = [...new Set(ICONS)].sort().map((name) => `    '${name}': '${toInlineSvg(name)}'`);
const out = `/*
 * GENERATED by scripts/generate-tabler-icons.cjs - do not edit by hand.
 * Verbatim SVGs from @tabler/icons ${pkg.version} (outline set), MIT License,
 * Copyright (c) 2020-2026 Paweł Kuna. https://tabler.io/icons
 */
export const TABLER_ICONS = {
${entries.join(',\n')}
} as const;

export type TablerIconName = keyof typeof TABLER_ICONS;

export function tablerIcon(name: TablerIconName): string {
    return TABLER_ICONS[name];
}
`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, out);
console.log(`Wrote ${entries.length} icons to ${path.relative(root, outFile)}`);
