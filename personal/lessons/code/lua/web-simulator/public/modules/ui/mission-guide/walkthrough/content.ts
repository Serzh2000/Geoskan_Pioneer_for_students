/** Stable per-lesson order, so the right answer's position carries no pattern (authored order alternated by lesson parity). */
export function shuffleChoices(content: TopicContent, seed: string): TopicContent {
    let state = 2166136261;
    for (const char of seed) state = Math.imul(state ^ char.charCodeAt(0), 16777619) >>> 0;
    const order = content.choices.map((_, index) => index);
    for (let i = order.length - 1; i > 0; i--) {
        state = (Math.imul(state, 1664525) + 1013904223) >>> 0;
        const j = state % (i + 1);
        [order[i], order[j]] = [order[j], order[i]];
    }
    return { ...content, choices: order.map(index => content.choices[index]), correct: order.indexOf(content.correct) };
}

export function getWalkthroughContent(lesson: WalkthroughLesson): TopicContent {
    if ('academy' in lesson && lesson.academy) return shuffleChoices(lesson.academy.teaching, lesson.id);
    const content = WALKTHROUGH_TOPICS[getWalkthroughTopic(lesson)];
    if (!content) throw new Error(`Missing walkthrough content: ${lesson.id}`);
    return shuffleChoices(content, lesson.id);
}
