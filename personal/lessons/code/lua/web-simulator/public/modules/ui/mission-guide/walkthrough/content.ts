export function getWalkthroughTopic(lesson: WalkthroughLesson): string {
    const topic = 'topicId' in lesson ? lesson.topicId : lesson.id.replace(/^(lua|python|py)-/, '');
    return ({ arm: 'preflight', 'point-wait': 'point-confirm', land: 'landing' } as Record<string, string>)[topic] || topic;
}

