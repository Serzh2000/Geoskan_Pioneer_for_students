-- приоритет: умножение выполняется раньше сложения
local a = 2 + 3 * 4
-- остаток от деления (modulo)
local r = 5 % 2
-- возведение 2 в степень 3 (результат всегда вещественный)
local p = 2 ^ 3
print(a, r, p)        -- 14  1  8.0
-- сравнения дают булево значение
local eq = (a == 14)
local gt = (a > 10)
print(eq, gt)         -- true  true
-- "целочисленное" деление с округлением вниз
local q = math.floor(17 / 4)
-- евклидова длина вектора
local len = math.sqrt(3*3 + 4*4)
print(q, len)         -- 4  5.0
